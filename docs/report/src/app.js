// Boot: read the inlined data, render both tabs, route on #results / #architecture.
(function (root) {
  'use strict';
  const doc = root.document;
  const data = JSON.parse(doc.getElementById('report-data').textContent);
  const VIEWS = ['results', 'architecture'];

  function route() {
    const name = VIEWS.includes(root.location.hash.slice(1)) ? root.location.hash.slice(1) : 'results';
    for (const v of VIEWS) {
      doc.getElementById(`view-${v}`).hidden = v !== name;
      const tab = doc.getElementById(`tab-${v}`);
      if (v === name) tab.setAttribute('aria-current', 'page'); else tab.removeAttribute('aria-current');
    }
    if (name === 'architecture') root.TF.arch.render();  // fit the figure to the now visible width
  }

  root.TF.results.render(doc.getElementById('view-results'), data);
  root.TF.arch.init(doc.getElementById('view-architecture'), data);
  doc.getElementById('foot').textContent = `Generated by scripts/report.py on ${data.generated} from runs/ and configs/. `
    + 'Numbers on this page come only from run directories; comments come from docs/report/notes.yaml.';
  root.addEventListener('hashchange', route);
  route();
})(window);
